/**
 * DBA Layer 3 — Schema Authoring, through the SDK.
 *
 * Schema is authored as Fluent SOURCE, never as raw inserts into
 * `sys_db_object` / `sys_dictionary`. Two reasons, both already paid for in
 * this repo:
 *
 *   - REST is a global-tier writer. `sys_scope` on an insert is accepted and
 *     silently demoted to global (trap #69, §33 E4), so a table "created in the
 *     application scope" over the Table API is a global table that looks
 *     correct in the response.
 *   - There is no REST endpoint that creates a table. Inserting the metadata
 *     rows by hand produces something shaped like a table with none of the
 *     artifacts the platform generates alongside one, and nothing versioned.
 *
 * ── THE FLUENT SURFACE, READ OFF THE INSTALLED SDK (4.10.1) ──────────────────
 *
 * Not from memory and not from the docs site — from
 * `node_modules/@servicenow/sdk-core/dist/db/Table.d.ts` in this workspace:
 *
 *   Table({ name, extends, label, display, extensible, actions, audit,
 *           attributes, index, readOnly, textIndex, allowWebServiceAccess,
 *           allowNewFields, allowUiActions, accessibleFrom, autoNumber, schema })
 *
 * Two findings worth recording against the runbook's assumptions:
 *
 *   - `index` IS available on 4.10.1, as a Table OPTION —
 *     `index: [{ name?, unique, element }]` — not as a separate `Index()`
 *     artifact. The runbook said to verify Index support on the pinned version
 *     and fall back to guided steps; no fallback is needed for CREATION.
 *   - `augments: string` is present on 4.10.1 too, so the table-augments
 *     pattern for OOTB tables is available on this version. It is NOT exercised
 *     here — this phase was scoped to a custom table in our own scope — so the
 *     augment path below is generated and BUILD-checked only, and is reported
 *     as unproven rather than as working.
 *
 * Columns come from `@servicenow/sdk/core`: StringColumn, IntegerColumn,
 * BooleanColumn, ReferenceColumn, ChoiceColumn-style `choices` on a
 * StringColumn, DateTimeColumn, DecimalColumn.
 *
 * ── WHAT THIS PIPELINE REFUSES TO DO ─────────────────────────────────────────
 *
 * Nothing here is generated by the model. A table spec is structured input and
 * the source is DERIVED from it in code — the project's standing rule that a
 * thing the instance or the spec already states precisely is never asked of a
 * non-deterministic generator.
 */

