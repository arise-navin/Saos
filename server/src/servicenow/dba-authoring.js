/* ── spec validation, pure ────────────────────────────────────────────────── */

/** §1.7, enforced at authoring time rather than discovered at build time. */
export const MAX_TABLE_NAME = 30;

/*
 * Must start with a letter, end in a letter or digit, lowercase/digits/
 * underscores between. The optional group matters: the first form written here
 * required at least TWO characters, so a legal single-letter column was
 * rejected with "not a valid column name" — and that message then masked the
 * real errors in every spec that also had one.
 */
const NAME_RE = /^[a-z]([a-z0-9_]*[a-z0-9])?$/;

/**
 * Validate and normalise a table spec.
 *
 * Every rule here is one the SDK or the platform enforces later and more
 * obscurely. Failing at the spec is the difference between "name too long" and
 * a build diagnostic pointing at generated source the caller never wrote.
 */
/**
 * The rules a caller must plan against — A4, stated as DATA rather than prose.
 *
 * The tool schema and the preflight both read this, so the constraints a spec
 * will be judged by are the same ones the caller was told about. A constraint
 * discovered by failing into it is a constraint that was documented badly.
 */
/** The live, instance-derived constraints — the scope is read, never assumed. */
export async function liveTableConstraints() {
  return tableSpecConstraints(await currentScope());
}

export function tableSpecConstraints(scope = null) {
  return {
    namePrefix: scope ? `${scope}_` : null,
    maxNameLength: MAX_TABLE_NAME,
    charactersLeftForName: scope ? Math.max(0, MAX_TABLE_NAME - scope.length - 1) : null,
    namePattern: 'lowercase letters, digits and underscores; starts with a letter, ends with a letter or digit',
    columnTypes: Object.keys(COLUMN_EMITTERS),
    typeSynonyms: TYPE_SYNONYMS,
    extendsDefault: null,
    extendsNote: 'Tables are STANDALONE by default. `extends` is opt-in and is only set when the caller asks for it '
      + '— an unrequested `extends: "task"` silently inherits ~40 columns, a display value and platform business '
      + 'rules the caller never asked for.',
    autoNormalized: ['scope prefix', 'name length', 'unambiguous type synonyms'],
    normalizationNote: 'These are corrected automatically and REPORTED, so the approval gate shows the spec that '
      + 'will actually be built. Nothing is renamed silently.',
  };
}

/**
 * A3 — apply the safe corrections, and say what was corrected.
 *
 * Pure. Returns the corrected spec plus a list of what changed, so `createTable`
 * can put the corrections in front of the user at the approval gate. The point
 * is that a caller should not have to round-trip through a rejection to learn a
 * rule the tool could simply have applied — but equally, a rename the user
 * never sees is a rename they cannot object to.
 */
export function normalizeTableSpec(spec = {}, { scope } = {}) {
  const corrections = [];
  const out = { ...spec };

  let name = String(spec.name || '').trim().toLowerCase();
  const given = name;

  if (scope && name && !name.startsWith(`${scope}_`)) {
    // A bare `emp_assets` is what a caller naturally writes; the prefix is a
    // platform requirement, not a design decision they made.
    name = `${scope}_${name.replace(/^_+/, '')}`;
    corrections.push({ what: 'name', from: given, to: name, why: `a scoped table name must start with "${scope}_"` });
  }
  if (name.length > MAX_TABLE_NAME) {
    const prefix = scope ? `${scope}_` : '';
    const room = Math.max(1, MAX_TABLE_NAME - prefix.length);
    const stem = name.slice(prefix.length).slice(0, room).replace(/[^a-z0-9]+$/, '');
    const shortened = `${prefix}${stem}`;
    corrections.push({
      what: 'name', from: name, to: shortened,
      why: `table names are capped at ${MAX_TABLE_NAME} characters`,
    });
    name = shortened;
  }
  if (name !== given) out.name = name;

  const fields = Array.isArray(spec.fields) ? spec.fields : [];
  out.fields = fields.map((f) => {
    const raw = String(f?.type ?? '').trim().toLowerCase();
    const canonical = TYPE_SYNONYMS[raw];
    if (canonical && canonical !== raw) {
      corrections.push({
        what: `fields.${f?.name ?? '(unnamed)'}.type`, from: f?.type, to: canonical,
        why: `"${raw}" is an unambiguous synonym for "${canonical}"`,
      });
      return { ...f, type: canonical };
    }
    return raw && raw !== f?.type ? { ...f, type: raw } : f;
  });

  return { spec: out, corrections };
}

export function validateTableSpec(spec = {}, { scope } = {}) {
  const errors = [];
  const name = String(spec.name || '').trim().toLowerCase();

  if (!scope) errors.push('No application scope is configured; a scoped table cannot be named without one.');
  if (!name) errors.push('A table name is required.');
  if (name && !NAME_RE.test(name)) {
    errors.push(`"${name}" is not a valid table name: lowercase letters, digits and underscores only, starting with `
      + 'a letter and ending in a letter or digit.');
  }
  if (scope && name && !name.startsWith(`${scope}_`)) {
    errors.push(`A scoped table name must start with the scope prefix "${scope}_". Got "${name}".`);
  }
  if (name.length > MAX_TABLE_NAME) {
    errors.push(`Table names are capped at ${MAX_TABLE_NAME} characters; "${name}" is ${name.length}. `
      + `With the "${scope}_" prefix that leaves ${Math.max(0, MAX_TABLE_NAME - String(scope).length - 1)} characters for the table's own name.`);
  }

  const fields = Array.isArray(spec.fields) ? spec.fields : [];
  if (!fields.length) errors.push('A table needs at least one column.');

  const seen = new Set();
  for (const f of fields) {
    const el = String(f?.name || '').trim().toLowerCase();
    if (!el) { errors.push('A column with no name was given.'); continue; }
    if (!NAME_RE.test(el)) errors.push(`"${el}" is not a valid column name.`);
    if (seen.has(el)) errors.push(`Column "${el}" is defined twice.`);
    seen.add(el);
    if (!COLUMN_EMITTERS[f.type]) {
      errors.push(`Column "${el}" has type "${f.type}", which this authoring layer does not emit. `
        + `Supported: ${Object.keys(COLUMN_EMITTERS).join(', ')}.`);
    }
    if (f.type === 'reference' && !f.reference) errors.push(`Reference column "${el}" must name the table it points at.`);
    if (f.type === 'choice' && !(f.choices && Object.keys(f.choices).length)) {
      errors.push(`Choice column "${el}" must supply choices.`);
    }
  }

  if (spec.display && !seen.has(String(spec.display).toLowerCase())) {
    errors.push(`display: "${spec.display}" is not one of the columns defined on this table.`);
  }

  return {
    ok: errors.length === 0,
    errors,
    normalized: {
      name,
      label: spec.label || name,
      extends: spec.extends || null,
      display: spec.display ? String(spec.display).toLowerCase() : null,
      // §1.7: without this, the Table API answers 403 "User Not Authorized" on
      // a table whose ACLs are perfectly correct. Default ON, because a table
      // NHA cannot read back is a table NHA cannot verify it created.
      allowWebServiceAccess: spec.allowWebServiceAccess !== false,
      accessibleFrom: spec.accessibleFrom || 'package_private',
      extensible: Boolean(spec.extensible),
      audit: Boolean(spec.audit),
      autoNumber: spec.autoNumber || null,
      index: Array.isArray(spec.index) ? spec.index : [],
      fields: fields.map((f) => ({
        name: String(f.name).trim().toLowerCase(),
        type: f.type,
        label: f.label || String(f.name).trim(),
        maxLength: f.maxLength ?? null,
        mandatory: Boolean(f.mandatory),
        default: f.default ?? null,
        reference: f.reference ?? null,
        choices: f.choices ?? null,
        unique: Boolean(f.unique),
      })),
      acls: Array.isArray(spec.acls) ? spec.acls : [],
    },
  };
}

/* ── code generation, pure ────────────────────────────────────────────────── */

const lit = (v) => JSON.stringify(v);

const COLUMN_EMITTERS = {
  string: (f) => `StringColumn({ label: ${lit(f.label)}${f.maxLength ? `, maxLength: ${Number(f.maxLength)}` : ''}${f.mandatory ? ', mandatory: true' : ''}${f.unique ? ', unique: true' : ''}${f.default != null ? `, default: ${lit(String(f.default))}` : ''} })`,
  integer: (f) => `IntegerColumn({ label: ${lit(f.label)}${f.mandatory ? ', mandatory: true' : ''}${f.default != null ? `, default: ${Number(f.default)}` : ''} })`,
  boolean: (f) => `BooleanColumn({ label: ${lit(f.label)}${f.default != null ? `, default: ${f.default === true || f.default === 'true'}` : ''} })`,
  reference: (f) => `ReferenceColumn({ label: ${lit(f.label)}, referenceTable: ${lit(f.reference)}${f.mandatory ? ', mandatory: true' : ''} })`,
  choice: (f) => {
    const choices = Object.entries(f.choices)
      .map(([value, label]) => `                ${lit(value)}: { label: ${lit(typeof label === 'string' ? label : label?.label ?? value)} },`)
      .join('\n');
    return `StringColumn({
            label: ${lit(f.label)},
            maxLength: ${Number(f.maxLength) || 40},
            dropdown: 'none',${f.default != null ? `\n            default: ${lit(String(f.default))},` : ''}
            choices: {
${choices}
            },
        })`;
  },
  /*
   * A1 — `GlideDateTimeColumn` DOES NOT EXIST.
   *
   * That name was emitted here for every `datetime` column and
   * `@servicenow/sdk/core` does not export it — measured against the installed
   * sdk-core, whose 50 real `*Column` exports include `DateTimeColumn` and
   * `DateColumn` and nothing called `GlideDateTimeColumn` anywhere in the
   * package. So a date-typed column could never be authored: the build failed
   * on a reference to a factory that was never imported because it does not
   * exist, and the failure pointed at generated source nobody wrote.
   *
   * `date` was then recorded as "not supported", which was false — it was
   * unbuilt, the same mistake as §46/§47/H-2 one layer down. `DateColumn` is a
   * documented export and is emitted here.
   *
   * `sdk-column-types.test.js` now asserts every name in IMPORTS_FOR against
   * the SDK's own typings, so a factory that does not exist fails offline
   * instead of at install time.
   */
  date: (f) => `DateColumn({ label: ${lit(f.label)}${f.mandatory ? ', mandatory: true' : ''}${f.default != null ? `, default: ${lit(String(f.default))}` : ''} })`,
  datetime: (f) => `DateTimeColumn({ label: ${lit(f.label)}${f.mandatory ? ', mandatory: true' : ''}${f.default != null ? `, default: ${lit(String(f.default))}` : ''} })`,
  decimal: (f) => `DecimalColumn({ label: ${lit(f.label)}${f.mandatory ? ', mandatory: true' : ''} })`,
};

const IMPORTS_FOR = {
  string: 'StringColumn', integer: 'IntegerColumn', boolean: 'BooleanColumn',
  reference: 'ReferenceColumn', choice: 'StringColumn',
  date: 'DateColumn', datetime: 'DateTimeColumn', decimal: 'DecimalColumn',
};

/**
 * Type synonyms this layer will silently canonicalise — A3.
 *
 * Only where there is exactly ONE sensible reading. `text` is deliberately
 * absent: it could mean a short string or a multi-line text field, and guessing
 * between them would author the wrong column and call it a correction.
 */
const TYPE_SYNONYMS = {
  date_time: 'datetime', 'date-time': 'datetime', timestamp: 'datetime',
  glide_date_time: 'datetime', glide_date: 'date',
  bool: 'boolean', int: 'integer', number: 'integer', long: 'integer',
  float: 'decimal', double: 'decimal', currency: 'decimal',
  str: 'string', varchar: 'string',
  ref: 'reference',
};

/**
 * `$id` keys are a PROJECT-GLOBAL namespace (trap #1).
 *
 * A key copied from an example, or a bare `table`, collides with every other
 * source file in the workspace and the build fails naming a sys_id that appears
 * nowhere in the caller's source. Every key generated here is prefixed with the
 * table's own name, which is unique by construction because the platform will
 * not allow two tables to share one.
 */
/** The column types this layer emits, and the SDK factory each one uses. */
export const COLUMN_TYPES = Object.keys(COLUMN_EMITTERS);
export const columnFactoryFor = (type) => IMPORTS_FOR[type] ?? null;

export function idKey(tableName, suffix) {
  return `${tableName}_${suffix}`;
}

/** Deterministic Fluent source for a validated spec. No model involved. */
export function generateTableSource(normalized) {
  const t = normalized;
  const columnImports = [...new Set(t.fields.map((f) => IMPORTS_FOR[f.type]))].sort();
  const imports = ['Table', ...columnImports, ...(t.acls.length ? ['Acl'] : [])];

  const schema = t.fields
    .map((f) => `        ${f.name}: ${COLUMN_EMITTERS[f.type](f)},`)
    .join('\n');

  const opts = [
    `    $id: Now.ID[${lit(idKey(t.name, 'table'))}]`,
    `    name: ${lit(t.name)}`,
    `    label: ${lit(t.label)}`,
    ...(t.extends ? [`    extends: ${lit(t.extends)}`] : []),
    ...(t.display ? [`    display: ${lit(t.display)}`] : []),
    `    extensible: ${t.extensible}`,
    `    audit: ${t.audit}`,
    // §1.7 — the difference between a readable table and a 403 with perfect ACLs.
    `    allowWebServiceAccess: ${t.allowWebServiceAccess}`,
    `    accessibleFrom: ${lit(t.accessibleFrom)}`,
    ...(t.autoNumber ? [`    autoNumber: { prefix: ${lit(t.autoNumber.prefix)}, number: ${Number(t.autoNumber.number) || 1000}, numberOfDigits: ${Number(t.autoNumber.digits) || 7} }`] : []),
    ...(t.index.length
      ? [`    index: [${t.index.map((i) => `{ name: ${lit(i.name || `${t.name}_${[].concat(i.element).join('_')}`)}, unique: ${Boolean(i.unique)}, element: ${lit(i.element)} }`).join(', ')}]`]
      : []),
  ].join(',\n');

  const acls = t.acls.map((a, i) => {
    const parts = [
      `    $id: Now.ID[${lit(idKey(t.name, `acl_${a.operation}_${a.field ? String(a.field).replace(/\W/g, '') : 'table'}_${i}`))}]`,
      `    type: 'record'`,
      `    operation: ${lit(a.operation)}`,
      `    table: ${lit(t.name)}`,
      ...(a.field ? [`    field: ${lit(a.field)}`] : []),
      `    active: true`,
      `    adminOverrides: ${a.adminOverrides !== false}`,
      ...(a.roles?.length ? [`    roles: ${lit(a.roles)}`] : []),
      ...(a.condition ? [`    condition: ${lit(a.condition)}`] : []),
      `    description: ${lit(a.description || `${a.operation} access to ${t.name}${a.field ? `.${a.field}` : ''}`)}`,
    ].join(',\n');
    return `Acl({\n${parts},\n    })`;
  });

  /*
   * THE NAMED EXPORT IS MANDATORY, and its name must equal the table's.
   *
   * MEASURED — the first version emitted a bare `Table({...})` and `now-sdk
   * build` refused it:
   *
   *   TS213: Table definition should be exported as a named export with the
   *          name 'x_2002152_nwforge_asset'
   *
   * This is exactly what the offline build exists to catch (§5: build is free
   * and reaches nothing), and it is why nothing is installed before one passes.
   * A table name is always a valid JS identifier — lowercase, digits and
   * underscores, starting with a letter — so it can be used verbatim here.
   */
  return `// nowhelpassist-dba: ${t.name}
// Generated from a validated table spec by dba-authoring.js. Deterministic —
// no model output reaches this file. Edit the spec, not this source.
import { ${imports.join(', ')} } from '@servicenow/sdk/core'

export const ${t.name} = Table({
${opts},
    schema: {
${schema}
    },
})
${acls.length ? `\n${acls.join('\n\n')}\n` : ''}`;
}

/* ── adding a column to a table this application already owns ─────────────── */

/**
 * Which of the three authoring paths a column belongs on.
 *
 * NowForge could add a column to a NEW table (baked into `createTable`) and to
 * somebody else's OOTB table (`augmentTable`), and had no path for the case in
 * between — an existing custom table it owns. That gap surfaced as "that
 * process isn't supported", which was wrong: it was unbuilt, not unsupported.
 *
 * The routing is decided from two facts, both read live: does the table exist on
 * the bound instance, and does this application's Fluent source define it?
 */
export async function classifyColumnTarget(tableName) {
  const scope = await currentScope();
  const onInstance = (await metaQuery('sys_db_object', { query: `name=${tableName}`, fields: 'sys_id,name,sys_scope,super_class.name', max: 1 }))[0] || null;
  const found = await findTableSource(tableName);
  const ourScopeId = (await resolveScopeId(scope).catch(() => ({ scopeId: null }))).scopeId;
  const inOurScope = Boolean(onInstance) && onInstance.sys_scope === ourScopeId;

  if (!onInstance && !found.definedIn) {
    return {
      route: 'create_table', tableName, scope,
      reason: `${tableName} does not exist on this instance and no source defines it. Creating it is dba_create_table.`,
    };
  }
  if (found.definedIn) {
    return {
      route: 'in_scope_source', tableName, scope,
      sourceFile: found.definedIn.file,
      existsOnInstance: Boolean(onInstance),
      reason: `${tableName} is defined by this application's Fluent source, so a column is added by editing that `
            + 'source and reinstalling — not by writing to sys_dictionary.',
    };
  }
  if (inOurScope) {
    /*
     * Ours by scope, but nothing in our source declares it — so it was created
     * on the instance directly rather than by this application. Inserting a
     * column into sys_dictionary would work until the next install, which
     * reconciles the app to its source and would take the column with it.
     * Adopting the table into source first is the only path that does not
     * create a divergence, and that is a deliberate act, not a side effect.
     */
    return {
      route: 'unmanaged_in_scope', tableName, scope,
      existsOnInstance: true,
      reason: `${tableName} is in this application's scope but NO Fluent source declares it — it was created on the `
            + 'instance directly, not by this application. Adding a column over REST would put it on the instance '
            + 'while the source stayed silent, and the next install would remove it again. Adopt the table into '
            + 'source first, then add the column through the normal path.',
      offer: 'adopt-into-source',
    };
  }
  return {
    route: 'augment', tableName, scope,
    existsOnInstance: true,
    targetScope: onInstance.sys_scope,
    reason: `${tableName} belongs to another scope, so a column is added through the table-augments pattern `
          + '(dba_augment_table) and the base object is never edited.',
  };
}

/* ── one routing table, for every column verb ─────────────────────────────── */

/**
 * The verbs that act on a column of an existing table.
 *
 * Named as a set because the whole point of what follows is that a FOURTH verb
 * cannot be added without deciding what it does on all four routes.
 */
export const COLUMN_VERBS = ['add', 'modify', 'remove'];

/**
 * What each verb does on each route — the third fix for one bug class.
 *
 * ── WHY THIS IS A TABLE AND NOT AN IF-CHAIN PER VERB ─────────────────────────
 *
 * Routing was wired for `add` (§46), then again, separately, for `remove`
 * (§47), and `modify` dead-ended into "that process isn't supported" (H-2).
 * Three appearances of the same mistake: treating routing as a property of the
 * VERB, when it is a property of the TARGET. `classifyColumnTarget` already
 * reads the target once and answers the same way whoever asks; what was missing
 * was one place that says what each verb then does with that answer.
 *
 * So the decision is a table, it is exhaustive, and a verb or route missing
 * from it THROWS rather than falling through to a default. A fourth verb cannot
 * silently diverge, because there is nothing for it to silently diverge into.
 *
 * `proceed` says only where the work happens. It never says whether the work is
 * ALLOWED — every destructive verb still goes through `destructiveGate`
 * afterwards, and `modify` still refuses its own irreversible half. Routing and
 * gating are separate questions and are kept that way deliberately.
 */
const COLUMN_ROUTE_DECISIONS = {
  in_scope_source: {
    add: { proceed: true },
    modify: { proceed: true },
    remove: { proceed: true },
  },
  augment: {
    // The base object is never edited; a column is attached through the
    // table-augments pattern, which is its own tool.
    add: { proceed: false, redirect: 'dba_augment_table' },
    modify: { proceed: false, redirect: 'dba_augment_table' },
    // A drop still routes here: the column being dropped is OURS, attached to
    // someone else's table, so the gate — not the route — is what governs it.
    remove: { proceed: true },
  },
  create_table: {
    add: { proceed: false, redirect: 'dba_create_table' },
    modify: { proceed: false, redirect: 'dba_create_table' },
    remove: { proceed: false, redirect: null },
  },
  unmanaged_in_scope: {
    add: { proceed: false, offer: 'adopt-into-source' },
    modify: { proceed: false, offer: 'adopt-into-source' },
    remove: { proceed: false, offer: 'adopt-into-source' },
  },
};

/**
 * Decide what `verb` does with an already-classified `route`.
 *
 * Pure, so the symmetry between the verbs is testable without an instance —
 * which is the only way a claim like "all three route identically" stays true
 * a month from now.
 */
export function columnRouteDecision(route, verb) {
  if (!COLUMN_VERBS.includes(verb)) {
    throw Object.assign(new Error(
      `"${verb}" is not one of the column verbs (${COLUMN_VERBS.join(', ')}). Routing is decided from the TARGET, `
      + 'so a new verb must be added to COLUMN_ROUTE_DECISIONS explicitly rather than inheriting a default — '
      + 'inheriting a default is how add, remove and modify came to disagree three separate times.'
    ), { status: 500 });
  }
  const row = COLUMN_ROUTE_DECISIONS[route];
  if (!row) {
    throw Object.assign(new Error(
      `"${route}" is not a known column route (${Object.keys(COLUMN_ROUTE_DECISIONS).join(', ')}).`
    ), { status: 500 });
  }
  return row[verb];
}

/**
 * `dba.addField` — add a column to an in-scope, SDK-managed table.
 *
 * Source is edited, the workspace is rebuilt offline, the guards run, the app
 * is installed, and the result is read back off the instance. The read-back
 * checks two things, not one: that the column is live with the right type, AND
 * that the source and the instance now agree — because a change to SDK-managed
 * schema is not finished until they do.
 */
export async function addField(tableName, field, emit = () => {}, { dryRun = false } = {}) {
  const scope = await currentScope();

  const route = await classifyColumnTarget(tableName);
  if (!columnRouteDecision(route.route, 'add').proceed) {
    return { ok: false, stage: 'route', route, errors: [route.reason] };
  }

  // Validate the column the same way createTable does — one emitter, one set of
  // rules, so a column added later cannot be shaped differently from one baked
  // in at creation.
  const el = String(field?.name || '').trim().toLowerCase();
  const errors = [];
  if (!el || !NAME_RE.test(el)) errors.push(`"${field?.name}" is not a valid column name.`);
  if (!COLUMN_EMITTERS[field?.type]) {
    errors.push(`Column "${el}" has type "${field?.type}", which this authoring layer does not emit. `
      + `Supported: ${Object.keys(COLUMN_EMITTERS).join(', ')}.`);
  }
  if (field?.type === 'reference' && !field.reference) errors.push(`Reference column "${el}" must name the table it points at.`);
  if (field?.type === 'choice' && !(field.choices && Object.keys(field.choices).length)) errors.push(`Choice column "${el}" must supply choices.`);
  if (errors.length) return { ok: false, stage: 'spec', route, errors };

  const normalized = {
    name: el,
    type: field.type,
    label: field.label || field.name,
    maxLength: field.maxLength ?? null,
    /*
     * Additive means additive, on an EXISTING table with existing rows.
     * A mandatory column makes every row that predates it fail validation on
     * the next save; a unique index can fail to build against data already
     * there. Both are forced off, exactly as the augment path does.
     */
    mandatory: false,
    unique: false,
    default: field.default ?? null,
    reference: field.reference ?? null,
    choices: field.choices ?? null,
  };

  emit({ type: 'dba_preflight', table: tableName });
  const pre = await preflight({ operation: 'add_column', table: tableName });
  if (pre.verdict !== 'go') return { ok: false, stage: 'preflight', route, blockers: pre.blockers, preflight: pre };

  // Re-read live: a cache never drives a write.
  const already = await metaQuery('sys_dictionary', { query: `name=${tableName}^element=${el}`, fields: 'element,internal_type', max: 1 });
  if (already.length) {
    return {
      ok: false, stage: 'preflight', route,
      errors: [`${tableName} already has a column "${el}" (${already[0].internal_type}). Adding it again is not what `
             + 'this does; changing an existing column is a different operation.'],
    };
  }

  const file = route.sourceFile;
  const original = await fsp.readFile(file, 'utf8');
  let nextSource;
  try {
    nextSource = insertColumn(original, {
      column: el,
      emitted: COLUMN_EMITTERS[normalized.type](normalized),
      importName: IMPORTS_FOR[normalized.type],
    });
  } catch (err) {
    return { ok: false, stage: 'source', route, errors: [err.message] };
  }

  if (dryRun) return { ok: true, stage: 'dry-run', route, file, column: el, source: nextSource, preflight: pre, installed: false };

  await fsp.writeFile(file, nextSource, 'utf8');
  emit({ type: 'dba_source_edited', file });

  emit({ type: 'dba_building' });
  const built = await buildWorkspace();
  if (!built.ok) {
    // Put the source back exactly as it was. A failed edit must leave nothing
    // for the next install to pick up.
    await fsp.writeFile(file, original, 'utf8');
    const restored = (await fsp.readFile(file, 'utf8')) === original;
    return {
      ok: false, stage: 'build', route, diagnostics: extractDiagnostics(built), source: nextSource,
      sourceRestored: restored,
      message: 'now-sdk build failed; nothing was installed and the source was restored to its previous state.',
    };
  }

  emit({ type: 'dba_tier_check' });
  const tiers = await assertTiersAgree();
  emit({ type: 'dba_tiers_agree', host: tiers.host });

  emit({ type: 'dba_installing' });
  const installed = await installWorkspace({ timeoutMs: INSTALL_BOUND_MS });

  // A red install is only a claim (§44) — the read-back decides, on both paths.
  emit({ type: 'dba_verifying' });
  cacheClear('dba:');
  const verification = await verifyColumn(tableName, normalized, file);

  if (!installed.ok && !verification.ok) {
    return { ok: false, stage: 'install', route, diagnostics: extractDiagnostics(installed), file, verification };
  }

  return {
    ok: verification.ok,
    stage: verification.ok ? 'verified' : 'verification-failed',
    route: route.route,
    table: tableName,
    column: el,
    file,
    installedTo: tiers.host,
    preflight: pre,
    verification,
    permanence: pre.permanence ?? null,
    /*
     * The asymmetry, stated when it is cheap to hear rather than when it bites.
     * Adding is free and additive; removing is a gated irreversible drop. A user
     * told this at add time can decide; told it at remove time, they have
     * already committed.
     */
    asymmetry: `Adding ${el} was additive and safe. REMOVING it later is drop_column — an irreversible operation `
             + 'that creates no rollback context on any engine, and is gated behind an operator escalation, an '
             + 'export, a typed confirmation and an acknowledged impact report. Add freely; remove deliberately.',
    ...(installed.ok ? {} : {
      installReportedFailure: true,
      installTimedOut: installed.timedOut === true,
      installDiagnostics: extractDiagnostics(installed),
      reconciliation: installed.timedOut
        ? `The install did not answer within ${INSTALL_BOUND_MS / 60000} minutes, so the instance was read back `
          + 'instead of waiting. The read-back is the authority — it was NOT retried, because a retry would re-apply '
          + 'whatever the server had already done.'
        : 'The SDK reported a failure and the read-back found the column live. The read-back is the authority; do '
          + 'not retry without reading back first.',
    }),
    wholeAppNote: 'now-sdk install deploys the ENTIRE application (trap #8).',
  };
}

/**
 * Read the column back, and check that source and instance AGREE.
 *
 * The second half is the one that matters for SDK-managed schema. A column
 * present on the instance but absent from source is removed by the next
 * install; a column in source but absent from the instance never shipped.
 * Either way the two disagreeing is the defect, so it is reported as its own
 * finding rather than folded into "ok".
 */
export async function verifyColumn(tableName, normalized, file) {
  const rows = await metaQuery('sys_dictionary', {
    query: `name=${tableName}^element=${normalized.name}`,
    fields: 'element,name,internal_type,column_label,max_length,mandatory,reference,sys_scope',
    max: 1,
  });
  const got = rows[0] || null;

  const problems = [];
  if (!got) problems.push(`absent from ${tableName}'s dictionary on the instance`);
  else {
    const wantType = EXPECTED_INTERNAL_TYPE[normalized.type] ?? null;
    if (wantType && got.internal_type !== wantType) problems.push(`stored as ${got.internal_type}, expected ${wantType}`);
    if (normalized.reference && got.reference !== normalized.reference) problems.push(`references ${got.reference}, expected ${normalized.reference}`);
    if (got.mandatory === 'true') problems.push('stored mandatory — an added column must not invalidate existing rows');
  }

  const sourceText = await fsp.readFile(file, 'utf8').catch(() => '');
  const inSource = columnsInSchema(sourceText).includes(normalized.name);
  const agree = Boolean(got) && inSource;

  return {
    ok: problems.length === 0 && agree,
    table: tableName,
    column: normalized.name,
    onInstance: got ? { type: got.internal_type, label: got.column_label, maxLength: got.max_length, scope: got.sys_scope } : null,
    inSource,
    sourceAndInstanceAgree: agree,
    ...(problems.length ? { problems } : {}),
    ...(agree ? {} : {
      divergence: inSource
        ? 'The source declares the column and the instance does not have it — the install did not ship it.'
        : 'The instance has the column and the source does not declare it — the next install would REMOVE it.',
    }),
  };
}

/** What each emitted column type stores as, so a read-back can check the type rather than assume it. */
const EXPECTED_INTERNAL_TYPE = {
  string: 'string',
  integer: 'integer',
  boolean: 'boolean',
  reference: 'reference',
  choice: 'string',
  date: 'glide_date',
  datetime: 'glide_date_time',
  decimal: 'decimal',
};

/* ── modifying a column this application already owns ─────────────────────── */

/**
 * The column attributes this layer will change, and why only these.
 *
 * "Modify" is not one operation, and the H-2 gap was only ever in its SAFE
 * half. Splitting it here rather than at the call site is the point: the
 * dangerous halves already have correct, gated classifications in the
 * operations matrix (`decrease_column_width`, `change_column_type`,
 * `rename_column`), and nothing below can reach them.
 *
 *   label      display only. No stored value changes. Lands on
 *              sys_documentation.label — MEASURED end to end.
 *   hint       display only. Lands on sys_documentation.hint — but ONLY when
 *              emitted through the Documentation form; see DOCUMENTATION_FORM.
 *   help       display only, alongside hint on the same record.
 *   default    applies to rows created AFTER it; existing rows keep their
 *              value. Lands on sys_dictionary.default_value — MEASURED.
 *   maxLength  WIDENING only. Narrowing truncates every value that no longer
 *              fits and creates no rollback context — that is
 *              `decrease_column_width` and it stays gated.
 */
export const MODIFIABLE_OPTIONS = ['label', 'hint', 'help', 'default', 'maxLength'];

/**
 * The options that must travel together, and the measurement behind that.
 *
 * ── WHY `hint: "…"` ON A COLUMN IS SILENTLY DISCARDED ────────────────────────
 *
 * `hint?: string` and `help?: string` are declared on `Column` in sdk-core, and
 * `now-sdk build` accepts them without a diagnostic. They never arrive. A first
 * pass caught this the expensive way — a live install where `label` and
 * `default` landed and `sys_documentation.hint` stayed empty — and the
 * read-back refused to call it a success.
 *
 * The cheap proof is the BUILD ARTIFACT, which settles where the value is lost
 * without touching the instance at all. Building
 *
 *   u_name: StringColumn({ label: "Name", maxLength: 40,
 *                          hint: "BUILD PROBE HINT", help: "BUILD PROBE HELP" })
 *
 * emits dist/app/update/sys_documentation_…_u_name_en.xml containing
 *
 *   <help/>  <hint/>  <label>Name</label>
 *
 * — empty, before the instance is ever contacted. So this is a BUILD-time drop,
 * not an install-time or platform one.
 *
 * MEASURED on @servicenow/sdk 4.10.1 AND 4.11.2 (the latest at the time of
 * writing): both drop it identically, and `sdk-core/dist/db/` is byte-identical
 * between the two, so no upgrade fixes it. It is not a version bug.
 *
 * The form that DOES work is the documentation list — `label` may be a
 * `Documentation[]` rather than a string:
 *
 *   u_name: StringColumn({ label: [{ label: "Name", hint: "…", help: "…" }],
 *                          maxLength: 40 })
 *
 * which builds to <hint>…</hint> <help>…</help> <label>Name</label>. Verified
 * at build on BOTH 4.10.1 and 4.11.2, then verified live by read-back of
 * sys_documentation.
 *
 * The consequence for this layer: label, hint and help are ONE option as far as
 * the emitter is concerned. Setting any of them re-emits all three, carrying
 * the current values of the ones the caller did not ask to change — otherwise
 * setting a hint would blank the label.
 */
const DOCUMENTATION_FORM = ['label', 'hint', 'help'];

/** Which gated operation a refused change actually is, so the refusal can name it. */
const UNSAFE_MODIFY = {
  narrow: 'decrease_column_width',
  retype: 'change_column_type',
  rename: 'rename_column',
};

/**
 * Split a requested change into the half this layer performs and the half it refuses.
 *
 * Pure — `current` is a live `sys_dictionary` row (plus the documentation row's
 * hint), `requested` is the caller's change. Kept free of I/O so the safe/unsafe
 * boundary is testable without an instance, because that boundary is the whole
 * safety property of this feature.
 */
export function classifyColumnChange(current, requested = {}) {
  const safe = [];
  const refused = [];
  const noop = [];
  const unknown = [];

  const currentMax = Number(current?.max_length);
  const values = {
    label: current?.column_label ?? '',
    hint: current?.hint ?? '',
    help: current?.help ?? '',
    default: current?.default_value ?? '',
    maxLength: Number.isFinite(currentMax) ? currentMax : null,
  };

  for (const [option, to] of Object.entries(requested)) {
    if (to === undefined) continue;

    if (option === 'name') {
      if (String(to) !== String(current?.element)) {
        refused.push({
          option, operation: UNSAFE_MODIFY.rename, from: current?.element ?? null, to,
          reason: 'Renaming a column creates no rollback context, and every query, script and ACL naming the old '
                + 'column stops matching WITHOUT erroring. It is gated separately and is not part of modify.',
        });
      }
      continue;
    }
    if (option === 'type') {
      if (String(to) !== String(current?.internal_type)) {
        refused.push({
          option, operation: UNSAFE_MODIFY.retype, from: current?.internal_type ?? null, to,
          reason: 'A type change creates no rollback context, and data that does not fit the new type is lost in '
                + 'the conversion. It is gated separately and is not part of modify.',
        });
      }
      continue;
    }
    if (!MODIFIABLE_OPTIONS.includes(option)) {
      unknown.push({ option, to, reason: `"${option}" is not an attribute this layer changes. Modifiable: ${MODIFIABLE_OPTIONS.join(', ')}.` });
      continue;
    }

    const from = values[option];
    if (option === 'maxLength') {
      const want = Number(to);
      if (!Number.isFinite(want) || want <= 0) {
        unknown.push({ option, to, reason: `maxLength must be a positive number; got ${JSON.stringify(to)}.` });
        continue;
      }
      if (from != null && want < from) {
        refused.push({
          option, operation: UNSAFE_MODIFY.narrow, from, to: want,
          reason: `Narrowing ${current?.element} from ${from} to ${want} truncates every value that no longer fits `
                + 'and creates no rollback context. It is gated separately and is not part of modify.',
        });
        continue;
      }
      if (from != null && want === from) { noop.push({ option, value: want }); continue; }
      safe.push({ option, from, to: want });
      continue;
    }

    if (String(from ?? '') === String(to ?? '')) { noop.push({ option, value: to }); continue; }
    safe.push({ option, from: from ?? null, to });
  }

  return { safe, refused, noop, unknown };
}

/** Emit a column option as the literal the schema block will hold. */
function optionLiteral(option, value, type) {
  if (option === 'maxLength') return String(Number(value));
  if (option !== 'default') return lit(String(value));
  if (type === 'integer' || type === 'decimal') return String(Number(value));
  if (type === 'boolean') return String(value === true || value === 'true');
  return lit(String(value));
}

/**
 * Turn a set of applied changes into the literals `modifyColumn` will splice in.
 *
 * The one piece of real work here is folding label/hint/help into a single
 * `label: [{ … }]` — see DOCUMENTATION_FORM for why the flat `hint:` option is
 * not an option at all. `current` supplies the values the caller did not ask to
 * change, so setting a hint cannot blank a label.
 *
 * Pure, so the emitted shape is testable without a build.
 */
export function emitColumnOptions(applied, current = {}, type = 'string') {
  const set = {};
  const touchesDocs = applied.some((c) => DOCUMENTATION_FORM.includes(c.option));

  for (const change of applied) {
    if (DOCUMENTATION_FORM.includes(change.option)) continue;   // folded below
    set[change.option] = optionLiteral(change.option, change.to, type);
  }

  if (touchesDocs) {
    const requested = Object.fromEntries(applied.map((c) => [c.option, c.to]));
    const doc = {
      label: requested.label ?? current.label ?? '',
      hint: requested.hint ?? current.hint ?? '',
      help: requested.help ?? current.help ?? '',
    };
    // `language` is deliberately omitted: the project's now.config.json default
    // supplies it, and pinning one here would make every column single-language
    // by accident. Measured: the built record carries <language>en</language>
    // without it.
    const parts = [`label: ${lit(doc.label)}`];
    if (doc.hint) parts.push(`hint: ${lit(doc.hint)}`);
    if (doc.help) parts.push(`help: ${lit(doc.help)}`);
    // A label with no hint and no help stays a plain string — the simplest form
    // that works, and the one every generated column already uses.
    set.label = parts.length === 1 ? lit(doc.label) : `[{ ${parts.join(', ')} }]`;
  }

  return set;
}

/** The Fluent column type behind a stored `internal_type`, for emitting a default. */
const TYPE_FOR_INTERNAL = Object.fromEntries(
  Object.entries(EXPECTED_INTERNAL_TYPE).map(([k, v]) => [v, k]),
);

/**
 * `dba.modifyField` — change a column on an in-scope, SDK-managed table.
 *
 * ── H-2, AND WHY IT IS THE SAME FIX AS §46 AND §47 ───────────────────────────
 *
 * Add was wired, then remove was wired, and modify dead-ended into "that
 * process isn't supported" — which was wrong the same way both times before:
 * unbuilt, not unsupported. The cause each time was routing decided per VERB.
 * It is now decided once, from the target, in `columnRouteDecision`, and this
 * function is a consumer of that decision rather than a third copy of it.
 *
 * What it does NOT do is loosen anything. Narrowing and retyping are refused
 * here and stay behind the destructive gate, and the refusal names the gated
 * operation instead of quietly doing a smaller thing the caller did not ask
 * for. A change with any refused part is refused WHOLE — a partial application
 * would leave the caller believing a change landed that did not.
 */
export async function modifyField(tableName, change = {}, emit = () => {}, { dryRun = false } = {}) {
  const el = String(change?.name || '').trim().toLowerCase();
  if (!tableName || !el) {
    return { ok: false, stage: 'spec', errors: ['modifyField needs both a table and a column name.'] };
  }

  const route = await classifyColumnTarget(tableName);
  const decision = columnRouteDecision(route.route, 'modify');
  if (!decision.proceed) {
    return {
      ok: false, stage: 'route', route, errors: [route.reason],
      ...(decision.redirect ? { redirect: decision.redirect } : {}),
      ...(decision.offer ? { offer: decision.offer } : {}),
    };
  }

  // Re-read live: a cache never drives a write (guardrail §6).
  const [dictRows, docRows] = await Promise.all([
    metaQuery('sys_dictionary', {
      query: `name=${tableName}^element=${el}`,
      fields: 'element,name,internal_type,column_label,max_length,default_value,reference,mandatory',
      max: 1,
    }),
    metaQuery('sys_documentation', { query: `name=${tableName}^element=${el}`, fields: 'element,name,label,hint,help', max: 1 }).catch(() => []),
  ]);
  const current = dictRows[0]
    ? { ...dictRows[0], column_label: docRows[0]?.label ?? dictRows[0].column_label, hint: docRows[0]?.hint ?? '', help: docRows[0]?.help ?? '' }
    : null;
  if (!current) {
    return {
      ok: false, stage: 'preflight', route: route.route,
      errors: [`${tableName} has no column "${el}". Adding one is dba_add_field; this changes a column that already exists.`],
    };
  }

  const { name: _ignored, ...requested } = change;
  const split = classifyColumnChange(current, { ...requested, name: el });

  if (split.unknown.length) {
    return { ok: false, stage: 'spec', route: route.route, table: tableName, column: el, errors: split.unknown.map((u) => u.reason) };
  }
  if (split.refused.length) {
    /*
     * The refusal is the feature, not a gap in it. It names the real operation
     * so the caller can go through the gate rather than around it, and it does
     * NOT apply the safe part of a mixed request — a half-applied change the
     * caller believes was whole is worse than a clean refusal.
     */
    return {
      ok: false,
      stage: 'gated',
      route: route.route,
      table: tableName,
      column: el,
      irreversible: true,
      refused: split.refused,
      wouldHaveApplied: split.safe,
      statement: `${split.refused.map((r) => `Changing ${el}'s ${r.option} is ${r.operation}`).join('; ')}. `
               + 'These create no rollback context on any database engine, are refused by default, and are not part '
               + 'of modify. Nothing was changed — including the safe parts of this request, which are not applied '
               + 'on their own so that a partial change cannot be mistaken for the whole one.',
      doNotWorkAround: 'Do not offer to edit the Fluent source by hand as an alternative, and do not substitute a '
        + 'different change that happens to be permitted. Take the named operation through its gate.',
      requiredNext: split.refused.map((r) => `${r.operation} — dba_classify_operation and dba_preflight state what it requires`),
    };
  }
  if (!split.safe.length) {
    return {
      ok: true, stage: 'no-change', route: route.route, table: tableName, column: el,
      noop: split.noop,
      note: `${el} already holds every value requested; nothing was written and nothing was installed.`,
    };
  }

  emit({ type: 'dba_preflight', table: tableName });
  const pre = await preflight({ operation: 'modify_column', table: tableName, field: el });
  if (pre.verdict !== 'go') return { ok: false, stage: 'preflight', route: route.route, blockers: pre.blockers, preflight: pre };

  const fluentType = TYPE_FOR_INTERNAL[current.internal_type] ?? 'string';
  const set = emitColumnOptions(split.safe, {
    label: current.column_label ?? '',
    hint: current.hint ?? '',
    help: current.help ?? '',
  }, fluentType);

  const file = route.sourceFile;
  const original = await fsp.readFile(file, 'utf8');
  let edit;
  try {
    edit = modifyColumn(original, { column: el, set });
  } catch (err) {
    return { ok: false, stage: 'source', route: route.route, errors: [err.message] };
  }
  if (!edit.changed) {
    return { ok: false, stage: 'source', route: route.route, errors: [edit.reason] };
  }

  if (dryRun) {
    return {
      ok: true, stage: 'dry-run', route: route.route, table: tableName, column: el,
      file, applied: split.safe, sourceBefore: edit.before, sourceAfter: edit.after,
      source: edit.text, preflight: pre, installed: false,
    };
  }

  await fsp.writeFile(file, edit.text, 'utf8');
  emit({ type: 'dba_source_edited', file });

  emit({ type: 'dba_building' });
  const built = await buildWorkspace();
  if (!built.ok) {
    // Put the source back exactly as it was, the same way addField does.
    await fsp.writeFile(file, original, 'utf8');
    const restored = (await fsp.readFile(file, 'utf8')) === original;
    return {
      ok: false, stage: 'build', route: route.route, diagnostics: extractDiagnostics(built), source: edit.text,
      sourceRestored: restored,
      message: 'now-sdk build failed; nothing was installed and the source was restored to its previous state.',
    };
  }

  emit({ type: 'dba_tier_check' });
  const tiers = await assertTiersAgree();
  emit({ type: 'dba_tiers_agree', host: tiers.host });

  emit({ type: 'dba_installing' });
  const installed = await installWorkspace({ timeoutMs: INSTALL_BOUND_MS });

  // A red install is only a claim (§44) — the read-back decides, on both paths.
  emit({ type: 'dba_verifying' });
  cacheClear('dba:');
  const verification = await verifyColumnChange(tableName, el, split.safe, file);

  if (!installed.ok && !verification.ok) {
    return { ok: false, stage: 'install', route: route.route, diagnostics: extractDiagnostics(installed), file, verification };
  }

  return {
    ok: verification.ok,
    stage: verification.ok ? 'verified' : 'verification-failed',
    route: route.route,
    table: tableName,
    column: el,
    file,
    applied: split.safe,
    ...(split.noop.length ? { unchanged: split.noop } : {}),
    installedTo: tiers.host,
    preflight: pre,
    verification,
    permanence: pre.permanence ?? null,
    reversibility: `Every attribute changed here can be set back to its previous value with another modify — the `
      + `previous values are recorded above and in the audit ledger. This is NOT true of the changes modify `
      + `refuses: narrowing and retyping destroy data and cannot be undone.`,
    ...(installed.ok ? {} : {
      installReportedFailure: true,
      installTimedOut: installed.timedOut === true,
      installDiagnostics: extractDiagnostics(installed),
      reconciliation: installed.timedOut
        ? `The install did not answer within ${INSTALL_BOUND_MS / 60000} minutes, so the instance was read back `
          + 'instead of waiting. The read-back is the authority — it was NOT retried, because a retry would re-apply '
          + 'whatever the server had already done.'
        : 'The SDK reported a failure and the read-back found the change live. The read-back is the authority; do '
          + 'not retry without reading back first.',
    }),
    wholeAppNote: 'now-sdk install deploys the ENTIRE application (trap #8).',
  };
}

/**
 * Read the changed column back, and check that source and instance AGREE.
 *
 * Same two-part contract as `verifyColumn`: the values must be live on the
 * instance AND declared in the source, because a change present on only one
 * side is undone by the next install or never shipped at all.
 *
 * `label` and `hint` are stored on `sys_documentation`, not `sys_dictionary` —
 * measured on dev428633, `sys_dictionary` has no `hint` column and its
 * `column_label` is a `documentation_field` backed by that table. Reading the
 * label from the dictionary alone would report a stale value as agreement.
 */
export async function verifyColumnChange(tableName, element, applied, file) {
  const [dictRows, docRows] = await Promise.all([
    metaQuery('sys_dictionary', {
      query: `name=${tableName}^element=${element}`,
      fields: 'element,name,internal_type,column_label,max_length,default_value',
      max: 1,
    }),
    metaQuery('sys_documentation', { query: `name=${tableName}^element=${element}`, fields: 'element,name,label,hint,help', max: 1 }).catch(() => []),
  ]);
  const got = dictRows[0] || null;
  const doc = docRows[0] || null;

  const onInstance = {
    label: doc?.label ?? got?.column_label ?? null,
    hint: doc?.hint ?? null,
    help: doc?.help ?? null,
    default: got?.default_value ?? null,
    maxLength: got?.max_length != null ? Number(got.max_length) : null,
  };

  const problems = [];
  const checked = [];
  if (!got) problems.push(`${element} is absent from ${tableName}'s dictionary on the instance`);
  else {
    for (const change of applied) {
      const actual = onInstance[change.option];
      const agrees = change.option === 'maxLength'
        // The platform may widen further than asked (a minimum for the type);
        // it must never end up NARROWER than requested.
        ? Number(actual) >= Number(change.to)
        : String(actual ?? '') === String(change.to ?? '');
      checked.push({ option: change.option, requested: change.to, onInstance: actual, agrees });
      if (!agrees) problems.push(`${change.option} reads ${JSON.stringify(actual)} on the instance, expected ${JSON.stringify(change.to)}`);
    }
  }

  const sourceText = await fsp.readFile(file, 'utf8').catch(() => '');
  const inSource = columnsInSchema(sourceText).includes(element);
  const agree = Boolean(got) && inSource;

  return {
    ok: problems.length === 0 && agree,
    table: tableName,
    column: element,
    checked,
    onInstance,
    inSource,
    sourceAndInstanceAgree: agree,
    ...(problems.length ? { problems } : {}),
    ...(agree ? {} : {
      divergence: inSource
        ? 'The source declares the column and the instance does not have it — the install did not ship it.'
        : 'The instance has the column and the source does not declare it — the next install would REMOVE it.',
    }),
  };
}

/* ── the augment path: adding a column to an out-of-scope table ───────────── */

/**
 * E1 — the ONLY sanctioned way NowHelpAssist touches an OOTB table.
 *
 * The base object is never edited. `Table({ augments: '<table>' })` attaches
 * columns owned by THIS scope to a table owned by another, so the platform
 * records them as our application's files while the target's own definition is
 * untouched. A `CrossScopePrivilege` record declares the access our scope needs
 * to the target scope's resources.
 *
 * A column added this way must carry the authoring scope's prefix — the
 * platform namespaces cross-scope columns so two applications cannot collide on
 * `u_note`. That is enforced at the spec rather than discovered at build time.
 *
 * ADDITIVE ONLY, and structurally so rather than by convention: this function
 * emits a schema and nothing else. There is no path through it that drops,
 * renames, retypes or narrows anything — because undoing an augment is
 * `drop_column`, which creates no rollback context on any engine.
 */
export function validateAugmentSpec({ baseTable, fields = [] } = {}, { scope } = {}) {
  const errors = [];
  if (!scope) errors.push('No application scope is configured.');
  if (!baseTable || !NAME_RE.test(String(baseTable))) errors.push(`"${baseTable}" is not a valid table name.`);
  if (!fields.length) errors.push('An augment must add at least one column.');

  const seen = new Set();
  for (const f of fields) {
    const el = String(f?.name || '').trim().toLowerCase();
    if (!el) { errors.push('A column with no name was given.'); continue; }
    if (!NAME_RE.test(el)) errors.push(`"${el}" is not a valid column name.`);
    if (seen.has(el)) errors.push(`Column "${el}" is defined twice.`);
    seen.add(el);
    if (scope && !el.startsWith(`${scope}_`)) {
      errors.push(`Cross-scope column "${el}" must carry this scope's prefix "${scope}_". The platform namespaces `
        + 'columns added to another application\'s table so two applications cannot collide on the same short name.');
    }
    if (!COLUMN_EMITTERS[f.type]) {
      errors.push(`Column "${el}" has type "${f.type}", which this authoring layer does not emit.`);
    }
    if (f.type === 'reference' && !f.reference) errors.push(`Reference column "${el}" must name the table it points at.`);
    if (f.type === 'choice' && !(f.choices && Object.keys(f.choices).length)) errors.push(`Choice column "${el}" must supply choices.`);
  }

  return {
    ok: errors.length === 0,
    errors,
    normalized: {
      baseTable,
      fields: fields.map((f) => ({
        name: String(f.name).trim().toLowerCase(),
        type: f.type,
        label: f.label || String(f.name).trim(),
        maxLength: f.maxLength ?? null,
        // Forced off, and it matters: a mandatory column added to a table with
        // millions of existing rows makes every one of them fail validation on
        // the next save. Additive has to mean additive.
        mandatory: false,
        default: f.default ?? null,
        reference: f.reference ?? null,
        choices: f.choices ?? null,
        unique: false,
      })),
    },
  };
}

/** The Fluent source for an augment, plus the cross-scope privileges it declares. */
export function generateAugmentSource(normalized, { scope, targetScope = 'global', privileges = ['read', 'write'] } = {}) {
  const { baseTable, fields } = normalized;
  const columnImports = [...new Set(fields.map((f) => IMPORTS_FOR[f.type]))].sort();
  const schema = fields.map((f) => `        ${f.name}: ${COLUMN_EMITTERS[f.type](f)},`).join('\n');

  const priv = privileges.map((op) => [
    'CrossScopePrivilege({',
    `    $id: Now.ID[${lit(`${scope}_xsp_${baseTable}_${op}`)}],`,
    `    operation: ${lit(op)},`,
    "    status: 'allowed',",
    "    targetType: 'sys_db_object',",
    `    targetScope: ${lit(targetScope)},`,
    `    targetName: ${lit(baseTable)},`,
    '})',
  ].join('\n')).join('\n\n');

  return [
    `// nowhelpassist-dba: augment ${baseTable}`,
    '// Generated from a validated augment spec. The base object is NOT edited —',
    `// these columns are owned by this application and attached to ${baseTable}.`,
    '// Additive only: undoing an augment is drop_column, which is irreversible.',
    `import { Table, ${columnImports.join(', ')}, CrossScopePrivilege } from '@servicenow/sdk/core'`,
    '',
    /*
     * MEASURED: the named export must be the BASE TABLE's name, not a scoped
     * alias. `export const x_2002152_nwforge_augment_incident` failed the build
     * with TS213 "Table definition should be exported as a named export with
     * the name 'incident'". The rule is the same one that applies to a table
     * definition — the export name must match the table the block describes —
     * and for an augment that table is the one being augmented, not the app
     * doing the augmenting. Caught offline, before anything reached the instance.
     */
    `export const ${baseTable} = Table({`,
    `    $id: Now.ID[${lit(`${scope}_augment_${baseTable}`)}],`,
    `    augments: ${lit(baseTable)},`,
    '    schema: {',
    schema,
    '    },',
    '})',
    '',
    priv,
    '',
  ].join('\n');
}

/**
 * `dba.augmentTable` — the guarded pipeline, identical in shape to createTable.
 *
 * preflight(augment_column) → generate → build (offline) → tier + app guards →
 * install → read back off the BASE table → report.
 */
export async function augmentTable(spec, emit = () => {}, { dryRun = false } = {}) {
  const scope = await currentScope();
  const check = validateAugmentSpec(spec, { scope });
  if (!check.ok) return { ok: false, stage: 'spec', errors: check.errors };
  const a = check.normalized;

  emit({ type: 'dba_preflight', table: a.baseTable });
  const pre = await preflight({ operation: 'augment_column', table: a.baseTable });
  if (pre.verdict !== 'go') {
    return { ok: false, stage: 'preflight', blockers: pre.blockers, preflight: pre };
  }

  // Re-read live. The standing guardrail is that a cache never drives a write.
  const existing = await metaQuery('sys_dictionary', {
    query: `name=${a.baseTable}^elementIN${a.fields.map((f) => f.name).join(',')}`,
    fields: 'element,name', max: 50,
  });
  if (existing.length) {
    return {
      ok: false,
      stage: 'preflight',
      errors: [`${a.baseTable} already has ${existing.map((e) => e.element).join(', ')}. This augment would modify an `
             + 'existing column rather than add one, which is not what an augment is for.'],
    };
  }

  const targetScope = (await metaQuery('sys_db_object', { query: `name=${a.baseTable}`, fields: 'sys_scope', max: 1 }))[0]?.sys_scope || 'global';
  const source = generateAugmentSource(a, { scope, targetScope });
  const file = path.join(DBA_DIR, `augment_${a.baseTable}.now.ts`);

  if (dryRun) return { ok: true, stage: 'dry-run', baseTable: a.baseTable, file, source, preflight: pre, installed: false };

  await fsp.mkdir(DBA_DIR, { recursive: true });
  await fsp.writeFile(file, source, 'utf8');
  emit({ type: 'dba_source_written', file });

  emit({ type: 'dba_building' });
  const built = await buildWorkspace();
  if (!built.ok) {
    await fsp.rm(file, { force: true });
    return {
      ok: false, stage: 'build', diagnostics: extractDiagnostics(built), source,
      message: 'now-sdk build failed; nothing was installed and the generated source was removed.',
    };
  }

  emit({ type: 'dba_tier_check' });
  const tiers = await assertTiersAgree();
  emit({ type: 'dba_tiers_agree', host: tiers.host });

  emit({ type: 'dba_installing' });
  const installed = await installWorkspace({ timeoutMs: INSTALL_BOUND_MS });

  /*
   * A RED INSTALL IS ALSO ONLY A CLAIM.
   *
   * This repo's standing rule is that a green install proves nothing until the
   * work is read back. MEASURED here, the converse bites just as hard: the CLI
   * answered
   *
   *   "[now-sdk] ERROR: The deployment request timed out waiting for a response."
   *
   * with exit code 1 — and the deployment had SUCCEEDED. The column was live on
   * `incident`, the cross-scope privileges were in place, and four
   * sys_update_version rows recorded it. Adding a column to a table the size of
   * `incident` is a real ALTER; the server simply took longer than the client
   * was willing to wait.
   *
   * Trusting the exit code would report a failure for a change that happened —
   * and invite a retry that re-applies it. So the read-back runs either way and
   * IT decides; the install's own verdict is reported alongside, never instead.
   */
  emit({ type: 'dba_verifying' });
  cacheClear('dba:');
  const verification = await verifyAugment(a, { scope, targetScope });

  if (!installed.ok && !verification.ok) {
    return { ok: false, stage: 'install', diagnostics: extractDiagnostics(installed), source, file, verification };
  }

  return {
    ok: verification.ok,
    stage: verification.ok ? 'verified' : 'verification-failed',
    baseTable: a.baseTable,
    file,
    installedTo: tiers.host,
    preflight: pre,
    verification,
    permanence: pre.permanence ?? null,
    ...(installed.ok ? {} : {
      installReportedFailure: true,
      installDiagnostics: extractDiagnostics(installed),
      reconciliation: 'The SDK reported a failure and the read-back found the change live on the instance. The '
        + 'read-back is the authority: a deployment timeout is the client giving up on a request the server went on '
        + 'to complete. Do NOT retry on this shape of failure without reading back first — a retry would re-apply it.',
    }),
    wholeAppNote: 'now-sdk install deploys the ENTIRE application (trap #8).',
  };
}

/**
 * Read the augment back off the BASE table, and prove the base was not edited.
 *
 * Two separate claims, and the second is the one that matters most: the column
 * is live on the target, AND the target's own definition still belongs to its
 * original scope. An augment that quietly moved `incident` into our scope would
 * be a far worse outcome than one that failed.
 */
export async function verifyAugment(a, { scope, targetScope }) {
  const dict = await metaQuery('sys_dictionary', {
    query: `name=${a.baseTable}^elementIN${a.fields.map((f) => f.name).join(',')}`,
    fields: 'element,name,internal_type,column_label,max_length,mandatory,reference,sys_scope',
    max: 50,
  });
  const byElement = new Map(dict.map((d) => [d.element, d]));

  const fields = a.fields.map((f) => {
    const got = byElement.get(f.name);
    if (!got) return { field: f.name, ok: false, reason: `absent from ${a.baseTable}'s dictionary` };
    const problems = [];
    if (got.name !== a.baseTable) problems.push(`attached to ${got.name}, not ${a.baseTable}`);
    if (got.mandatory === 'true') problems.push('stored mandatory — an augment must not invalidate existing rows');
    return {
      field: f.name,
      ok: problems.length === 0,
      type: got.internal_type,
      label: got.column_label,
      columnScope: got.sys_scope,
      ...(problems.length ? { problems } : {}),
    };
  });

  const base = (await metaQuery('sys_db_object', { query: `name=${a.baseTable}`, fields: 'name,sys_scope,sys_update_name', max: 1 }))[0] || null;
  const baseUntouched = Boolean(base) && base.sys_scope === targetScope;

  // A2 — the SDK-install signal. Never sys_update_xml, which is empty here.
  const versions = await readInstallVersionRecords(a.fields[0].name);

  return {
    ok: fields.every((f) => f.ok) && baseUntouched,
    baseTable: a.baseTable,
    fields,
    baseObject: {
      scope: base?.sys_scope ?? null,
      expectedScope: targetScope,
      untouched: baseUntouched,
      note: baseUntouched
        ? `${a.baseTable} is still owned by ${targetScope}; only the added columns belong to ${scope}.`
        : `${a.baseTable}'s own scope is ${base?.sys_scope} — expected ${targetScope}. The base object may have been modified.`,
    },
    updateVersions: { count: versions.count, types: versions.types, signal: versions.signal },
  };
}

/* ── the pipeline ─────────────────────────────────────────────────────────── */

async function currentScope() {
  const cfg = JSON.parse(await fsp.readFile(path.join(WORKSPACE_DIRS.workspace, 'now.config.json'), 'utf8'));
  return cfg.scope;
}

/**
 * `dba.createTable` — spec → validate → preflight → source → build → install → read back → audit.
 *
 * The order is not negotiable and the build is not optional. `now-sdk build` is
 * offline and free (§5), so there is no excuse for letting invalid source reach
 * the instance; and `install` ships the WHOLE application (trap #8), which this
 * reports rather than glossing.
 */
export async function createTable(spec, emit = () => {}, { dryRun = false } = {}) {
  const scope = await currentScope();
  const constraints = tableSpecConstraints(scope);

  /*
   * A3 — correct what is safely correctable BEFORE validating, so a caller does
   * not round-trip through a rejection to learn the scope prefix. A2 — then
   * validate the whole spec at once and return EVERY violation, never the first
   * one: a tool that rejects one rule at a time turns a five-field table into
   * five failed attempts, and the model burns a turn on each.
   */
  const { spec: normalizedSpec, corrections } = normalizeTableSpec(spec, { scope });
  const check = validateTableSpec(normalizedSpec, { scope });
  if (!check.ok) {
    return {
      ok: false,
      stage: 'spec',
      errors: check.errors,
      errorCount: check.errors.length,
      ...(corrections.length ? { corrections } : {}),
      constraints,
      note: 'Every violation in the spec is listed above — this is the complete set, not the first failure. '
        + 'Fix them together and call once more.',
    };
  }
  const t = check.normalized;
  if (corrections.length) {
    // Surfaced, never silent: the approval gate shows the spec that will be
    // built, so a rename is something the user can object to.
    emit({ type: 'dba_spec_normalized', corrections });
  }

  emit({ type: 'dba_preflight', table: t.name });
  const pre = await preflight({ operation: 'create_table', table: t.name });
  // `create_table` is additive: it is not in the destructive matrix, so an
  // unknown-operation verdict here is expected and is not a blocker. What IS
  // checked is that the name is free.
  const existing = await metaQuery('sys_db_object', { query: `name=${t.name}`, fields: 'sys_id,name', max: 1 });
  if (existing.length) {
    return {
      ok: false, stage: 'preflight',
      errors: [`A table named "${t.name}" already exists on this instance (${existing[0].sys_id}). `
             + 'Authoring would modify it rather than create it; pick another name or update it deliberately.'],
    };
  }

  const source = generateTableSource(t);
  const file = path.join(DBA_DIR, `${t.name}.now.ts`);

  if (dryRun) {
    return { ok: true, stage: 'dry-run', table: t.name, file, source, preflight: pre, installed: false, ...(corrections.length ? { corrections } : {}), constraints };
  }

  await fsp.mkdir(DBA_DIR, { recursive: true });
  await fsp.writeFile(file, source, 'utf8');
  emit({ type: 'dba_source_written', file });

  // OFFLINE VALIDATION. Nothing has reached the instance yet.
  emit({ type: 'dba_building' });
  const built = await buildWorkspace();
  if (!built.ok) {
    // A failed build must leave nothing behind, or the next unrelated install
    // ships this file.
    await fsp.rm(file, { force: true });
    const still = await fsp.readFile(file, 'utf8').catch(() => null);
    return {
      ok: false, stage: 'build',
      diagnostics: extractDiagnostics(built),
      source,
      cleanedUp: still === null,
      message: 'now-sdk build failed; nothing was installed and the generated source was removed.',
    };
  }

  /*
   * The tier check runs HERE — after the offline build proved the source is
   * valid, and before anything leaves this machine. Checking earlier would
   * refuse specs that were never going to install anyway; checking later is
   * too late, because the install is the thing that becomes untrue.
   */
  emit({ type: 'dba_tier_check' });
  const tiers = await assertTiersAgree();
  emit({ type: 'dba_tiers_agree', host: tiers.host });

  emit({ type: 'dba_installing' });
  const installed = await installWorkspace({ timeoutMs: INSTALL_BOUND_MS });

  // A red install is only a claim too — see augmentTable. A deployment timeout
  // is the client giving up on a request the server went on to complete, so the
  // read-back decides and the install's verdict is reported beside it.
  emit({ type: 'dba_verifying' });
  cacheClear('dba:');
  const verified = await verifyTable(t);

  if (!installed.ok && !verified.ok) {
    return { ok: false, stage: 'install', diagnostics: extractDiagnostics(installed), source, file, verification: verified };
  }

  return {
    ok: verified.ok,
    stage: verified.ok ? 'verified' : 'verification-failed',
    ...(installed.ok ? {} : {
      installReportedFailure: true,
      installDiagnostics: extractDiagnostics(installed),
      reconciliation: 'The SDK reported a failure and the read-back found the change live. The read-back is the '
        + 'authority; do not retry on this shape of failure without reading back first.',
    }),
    table: t.name,
    file,
    ...(corrections.length ? { corrections, correctionsNote: 'The spec was normalized before building; these are the changes the approval gate showed.' } : {}),
    standalone: !t.extends,
    ...(t.extends ? { extends: t.extends, extendsNote: 'This table EXTENDS another because the spec asked it to. Extension is never a default.' } : {}),
    preflight: pre,
    verification: verified,
    verifiedBy: 'independent read of sys_db_object and sys_dictionary over the Table API — not the SDK that installed it',
    installedTo: tiers.host,
    wholeAppNote: 'now-sdk install deploys the ENTIRE application, not just this table (trap #8). Every other '
                + 'artifact in the workspace was shipped too, and their sys_updated_on moved.',
  };
}

/**
 * Read the table back off the instance and compare it to what was asked for.
 *
 * A green install is a claim. This is the evidence — field by field, plus a
 * live Table API round trip, because `allowWebServiceAccess` is the one setting
 * whose absence produces a 403 that looks exactly like an ACL problem.
 */
export async function verifyTable(t) {
  const rows = await metaQuery('sys_db_object', {
    query: `name=${t.name}`, fields: 'sys_id,name,label,super_class.name,sys_scope,is_extendable', max: 1,
  });
  if (!rows.length) {
    return { ok: false, reason: `The install reported success but no sys_db_object row named "${t.name}" exists. The table was NOT created.` };
  }
  const row = rows[0];

  const dict = await metaQuery('sys_dictionary', {
    query: `name=${t.name}^elementISNOTEMPTY`,
    fields: 'element,internal_type,column_label,max_length,mandatory,reference',
    max: 500,
  });
  const byElement = new Map(dict.map((d) => [d.element, d]));

  const fieldChecks = t.fields.map((f) => {
    const got = byElement.get(f.name);
    if (!got) return { field: f.name, ok: false, reason: 'absent from sys_dictionary' };
    const mismatches = [];
    if (f.mandatory && got.mandatory !== 'true') mismatches.push(`mandatory asked true, stored ${got.mandatory}`);
    if (f.reference && got.reference !== f.reference) mismatches.push(`reference asked ${f.reference}, stored ${got.reference}`);
    if (f.maxLength && Number(got.max_length) !== Number(f.maxLength)) mismatches.push(`maxLength asked ${f.maxLength}, stored ${got.max_length}`);
    return { field: f.name, ok: mismatches.length === 0, type: got.internal_type, ...(mismatches.length ? { mismatches } : {}) };
  });

  const choiceFields = t.fields.filter((f) => f.type === 'choice');
  const choiceChecks = [];
  for (const f of choiceFields) {
    // eslint-disable-next-line no-await-in-loop
    const ch = await metaQuery('sys_choice', { query: `name=${t.name}^element=${f.name}`, fields: 'value,label,inactive', max: 100 });
    const wanted = Object.keys(f.choices);
    const got = ch.map((c) => c.value);
    const missing = wanted.filter((v) => !got.includes(v));
    choiceChecks.push({ field: f.name, wanted: wanted.length, stored: got.length, ok: missing.length === 0, ...(missing.length ? { missing } : {}) });
  }

  const aclRows = await metaQuery('sys_security_acl', {
    query: `name=${t.name}^ORnameSTARTSWITH${t.name}.`, fields: 'name,operation,active', max: 100,
  });

  // A2 — the install's own change record. NOT sys_update_xml, which is empty
  // after an application install and would report "no change" for this one.
  const versions = await readInstallVersionRecords(t.name);

  // The live round trip. §1.7: without allowWebServiceAccess the Table API
  // answers 403 "User Not Authorized" no matter how correct the ACLs are, so
  // this is the only check that proves the table is actually reachable.
  let webService = null;
  try {
    await table.query(t.name, { limit: 1, fields: 'sys_id', display: 'false' });
    webService = { reachable: true, note: 'A live Table API read succeeded, so allowWebServiceAccess took effect.' };
  } catch (err) {
    webService = {
      reachable: false, status: err.status ?? null, error: err.message,
      note: 'The table exists but is not reachable over REST. If allowWebServiceAccess was true this is an ACL '
          + 'problem; if it was false this is expected and is not a fault.',
    };
  }

  const fieldsOk = fieldChecks.every((c) => c.ok);
  const choicesOk = choiceChecks.every((c) => c.ok);
  const aclsOk = t.acls.length === 0 || aclRows.length >= t.acls.length;

  return {
    ok: fieldsOk && choicesOk && aclsOk && (t.allowWebServiceAccess ? webService.reachable : true),
    sys_id: row.sys_id,
    label: row.label,
    scope: row.sys_scope,
    extends: row['super_class.name'] || null,
    scopeHeld: row.sys_scope !== 'global' || !t.name.startsWith('x_'),
    fields: fieldChecks,
    fieldsOk,
    choices: choiceChecks,
    choicesOk,
    acls: { asked: t.acls.length, stored: aclRows.length, rows: aclRows.map((a) => `${a.name} [${a.operation}]`), ok: aclsOk },
    updateVersions: { count: versions.count, types: versions.types, signal: versions.signal, note: versions.note },
    webService,
  };
}

/** Remove a table authored here: delete the source, rebuild, reinstall. */
export async function removeAuthoredTable(name, emit = () => {}) {
  const file = path.join(DBA_DIR, `${name}.now.ts`);
  const existed = await fsp.readFile(file, 'utf8').catch(() => null);
  if (existed === null) return { ok: false, reason: `No source file for "${name}" under ${DBA_DIR}; this table was not authored here.` };
  await fsp.rm(file, { force: true });
  emit({ type: 'dba_source_removed', file });
  const built = await buildWorkspace();
  if (!built.ok) {
    await fsp.writeFile(file, existed, 'utf8');
    return { ok: false, stage: 'build', diagnostics: extractDiagnostics(built), restored: true };
  }
  const installed = await installWorkspace({ timeoutMs: INSTALL_BOUND_MS });
  log.info('dba', `removeAuthoredTable(${name}) install ok=${installed.ok}`);
  return { ok: installed.ok, stage: installed.ok ? 'removed' : 'install', file };
}

