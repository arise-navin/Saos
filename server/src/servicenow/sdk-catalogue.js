import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * THE SDK'S OWN CATALOGUE OF TRIGGERS AND ACTIONS, READ FROM THE SDK.
 *
 * ── WHY THIS EXISTS ──────────────────────────────────────────────────────────
 *
 * Everything the codegen prompt and the pre-build gates knew about actions came
 * from `docs/fluent-flow-cheatsheet.md` — a document a person wrote by reading
 * another document. It listed 18 actions. The installed SDK ships 33, and the
 * seven attachment actions the cheatsheet referred to only as "attachment
 * actions" have real names, real parameters and real outputs. A catalogue
 * transcribed by hand is a catalogue that is already drifting.
 *
 * The SDK states all of it, exactly, in machine-generated files:
 * `@servicenow/sdk-core/dist/external/flow/built-ins/**` — each action's
 * `$id` (the live `sys_hub_action_type_base` sys_id), its name, every input
 * with its `mandatory` flag, and every output with its EXACT casing. That is
 * the authority. This module reads it.
 *
 * ── WHY IT IS PARSED RATHER THAN IMPORTED ────────────────────────────────────
 *
 * The obvious implementation is `require()` the built-ins and read the objects.
 * It does not work, and the reason is worth writing down because it decides
 * what this repository can and cannot do:
 *
 *     function Action(_config, _body) { return undefined }
 *
 * — `sdk-core/dist/external/flow/Action.js`, verbatim. `Action()`,
 * `Trigger()`, `Flow()` and `Subflow()` all return `undefined` at run time.
 * The Fluent API is a COMPILE-TIME DSL: the definitions exist only as
 * TypeScript the SDK's build transform reads as source. There is no runtime
 * object model, so there is no way to build a flow programmatically, inspect
 * one, or ask the SDK what it supports. Source → build → install is not one
 * option among several; it is the only path the SDK offers.
 *
 * So the literals are parsed out of the generated files. They carry a header
 * saying "This file is auto-generated by sync-plugin-apis.ts — do not edit
 * directly", which is what makes a parser appropriate: the shape is machine
 * written and uniform.
 *
 * ── WHAT IT REFUSES TO DO ────────────────────────────────────────────────────
 *
 * If the SDK is not installed, or its layout has moved, this returns
 * `{ available: false, reason }` and NOT a catalogue. A caller then falls back
 * to the documented one and says which it used. An invented catalogue that
 * looks authoritative is worse than a missing one.
 */

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const WORKSPACE = path.resolve(__dirname, '../../fluent-workspace');

/** Where the SDK keeps its generated built-ins, relative to a node_modules root. */
const BUILT_INS = 'node_modules/@servicenow/sdk-core/dist/external/flow/built-ins';

export function builtInsDir(workspace = WORKSPACE) {
  const dir = path.join(workspace, BUILT_INS);
  return fs.existsSync(dir) ? dir : null;
}

/* ------------------------------------------------------------------ *
 * A small reader for the generated literals
 * ------------------------------------------------------------------ */

/** Index of the bracket closing the one at `open`, skipping strings. */
function matchFrom(text, open) {
  const pairsOf = { '(': ')', '{': '}', '[': ']' };
  if (!pairsOf[text[open]]) return -1;
  let depth = 0;
  for (let i = open; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === "'" || ch === '"' || ch === '`') {
      for (let j = i + 1; j < text.length; j += 1) {
        if (text[j] === '\\') { j += 1; continue; }
        if (text[j] === ch) { i = j; break; }
        if (j === text.length - 1) i = j;
      }
      continue;
    }
    if (pairsOf[ch]) depth += 1;
    else if (ch === ')' || ch === '}' || ch === ']') { depth -= 1; if (depth === 0) return i; }
  }
  return -1;
}

/** Top-level `key: value` entries of an object literal body. */
function entriesOf(body) {
  const out = [];
  let depth = 0;
  let start = 0;
  const parts = [];
  for (let i = 0; i < body.length; i += 1) {
    const ch = body[i];
    if (ch === "'" || ch === '"' || ch === '`') {
      for (let j = i + 1; j < body.length; j += 1) {
        if (body[j] === '\\') { j += 1; continue; }
        if (body[j] === ch) { i = j; break; }
      }
      continue;
    }
    if (ch === '{' || ch === '(' || ch === '[') depth += 1;
    else if (ch === '}' || ch === ')' || ch === ']') depth -= 1;
    else if (ch === ',' && depth === 0) { parts.push(body.slice(start, i)); start = i + 1; }
  }
  parts.push(body.slice(start));
  for (const part of parts) {
    const m = /^\s*(?:'([^']+)'|"([^"]+)"|([A-Za-z_$][\w$]*))\s*:\s*([\s\S]*)$/.exec(part);
    if (m) out.push({ key: m[1] ?? m[2] ?? m[3], value: m[4].trim() });
  }
  return out;
}

/** The object literal for `key:` inside `text`, or null. */
function blockFor(text, key) {
  const at = new RegExp(`(^|[,{\\s])${key}\\s*:\\s*\\{`, 'm').exec(text);
  if (!at) return null;
  const open = text.indexOf('{', at.index + at[0].length - 1);
  const close = matchFrom(text, open);
  return close < 0 ? null : text.slice(open + 1, close);
}

const stringProp = (text, key) => {
  const m = new RegExp(`${key}\\s*:\\s*'((?:[^'\\\\]|\\\\.)*)'`).exec(text);
  return m ? m[1].replace(/\\(.)/g, '$1') : null;
};

/**
 * One column block — `name: SomeColumn({ label: 'x', mandatory: true })`.
 *
 * The COLUMN CONSTRUCTOR is kept as the type: `TableNameColumn`,
 * `TemplateValueColumn`, `DocumentIdColumn` and so on say what the parameter
 * will accept, which a bare name does not.
 */
function columnsOf(block) {
  if (!block) return [];
  return entriesOf(block).map(({ key, value }) => {
    const call = /^\(0,\s*[\w.$]+\.([A-Za-z_$][\w$]*)\)\s*\(/.exec(value) || /^([A-Za-z_$][\w$]*)\s*\(/.exec(value);
    const open = value.indexOf('{');
    const options = open >= 0 ? value.slice(open, matchFrom(value, open) + 1) : '';
    return {
      name: key,
      column: call?.[1] ?? null,
      label: stringProp(options, 'label'),
      mandatory: /\bmandatory\s*:\s*true\b/.test(options),
      reference: stringProp(options, 'referenceTable') ?? stringProp(options, 'reference'),
      dependent: stringProp(options, 'dependent'),
    };
  }).filter((c) => c.name);
}

/** Parse one generated built-in file into its definition. */
export function parseBuiltIn(source, exportName) {
  const text = String(source || '');
  const marker = new RegExp(`exports\\.${exportName}\\s*=\\s*\\(0,\\s*[\\w.$]+\\)\\(\\{`).exec(text)
    || new RegExp(`exports\\.${exportName}\\s*=\\s*[\\w.$]+\\(\\{`).exec(text);
  if (!marker) return null;
  const open = text.indexOf('{', marker.index + marker[0].length - 1);
  const close = matchFrom(text, open);
  if (close < 0) return null;
  const body = text.slice(open + 1, close);
  return {
    key: exportName,
    /* The live sys_id of the action/trigger type record on every instance. */
    sysId: stringProp(body, '\\$id'),
    name: stringProp(body, 'name'),
    type: stringProp(body, 'type'),
    description: stringProp(body, 'description'),
    inputs: columnsOf(blockFor(body, 'inputs')),
    outputs: columnsOf(blockFor(body, 'outputs')),
  };
}

const camel = (file) => file.replace(/\.now\.js$/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function readDir(dir, { stripSuffix = null } = {}) {
  const out = [];
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.now.js'))) {
    const exportName = camel(file);
    const source = fs.readFileSync(path.join(dir, file), 'utf8');
    const parsed = parseBuiltIn(source, exportName);
    if (!parsed) continue;
    /* A trigger file exports `createdTrigger` but the API names it
     * `trigger.record.created`. The KEY is what a source writes; the export
     * name is an implementation detail of the generated file. */
    const key = stripSuffix && exportName.endsWith(stripSuffix)
      ? exportName.slice(0, -stripSuffix.length)
      : exportName;
    out.push({ ...parsed, key, exportName, file });
  }
  return out;
}

let cache = null;

/**
 * Every action and trigger the installed SDK defines.
 *
 * `{ available: false, reason }` when the SDK is not there — never a guess.
 */
export function sdkCatalogue({ workspace = WORKSPACE, refresh = false } = {}) {
  if (cache && !refresh) return cache;
  const dir = builtInsDir(workspace);
  if (!dir) {
    cache = { available: false, reason: `the SDK built-ins are not installed (${path.join(workspace, BUILT_INS)} does not exist); run npm install in the workspace`, actions: {}, triggers: {} };
    return cache;
  }
  try {
    const actionsDir = path.join(dir, 'actions/core');
    const triggersDir = path.join(dir, 'triggers');
    const actions = {};
    for (const a of readDir(actionsDir)) actions[a.key] = a;
    const triggers = {};
    /* Trigger files are named `<form>-trigger.now.js`; the export drops the
     * suffix, and the FAMILY is derived from the type the definition declares
     * rather than from the filename. */
    for (const t of readDir(triggersDir, { stripSuffix: 'Trigger' })) {
      triggers[t.key] = { ...t, family: familyOf(t.type) };
    }
    cache = {
      available: true,
      source: dir,
      actions,
      triggers,
      counts: { actions: Object.keys(actions).length, triggers: Object.keys(triggers).length },
    };
  } catch (err) {
    cache = { available: false, reason: `the SDK built-ins could not be read: ${err.message}`, actions: {}, triggers: {} };
  }
  return cache;
}

/** Which family a trigger type belongs to, by the type string the SDK declares. */
export function familyOf(type) {
  if (!type) return null;
  if (type.startsWith('record_')) return 'record';
  if (['daily', 'weekly', 'monthly', 'repeat', 'run_once', 'recurrence'].includes(type)) return 'scheduled';
  return 'application';
}

/** The action catalogue in the shape the design linter consumes. */
export function actionRules(catalogue = sdkCatalogue()) {
  if (!catalogue.available) return null;
  const out = {};
  for (const [key, a] of Object.entries(catalogue.actions)) {
    out[key] = {
      name: a.name,
      sysId: a.sysId,
      requires: a.inputs.filter((i) => i.mandatory).map((i) => i.name),
      optional: a.inputs.filter((i) => !i.mandatory).map((i) => i.name),
      inputs: a.inputs,
      outputs: a.outputs.map((o) => o.name),
    };
  }
  return out;
}

/**
 * The catalogue as the codegen prompt should see it.
 *
 * The cheatsheet teaches SHAPE — how a flow is written, which mistakes cost a
 * silent no-op. This teaches INVENTORY: every action the installed SDK
 * actually has, what each one requires, and the exact casing of what it
 * returns. The two are complementary, which is why this is added to the prompt
 * rather than replacing anything: a model told only the shape invents action
 * names, and a model told only the inventory writes `table` where the action
 * wants `table_name`.
 *
 * Returns '' when the SDK is not installed, so the prompt silently loses a
 * section rather than gaining a fabricated one.
 */
export function sdkPromptBlock(catalogue = sdkCatalogue()) {
  if (!catalogue.available) return '';
  const lines = [];
  lines.push('--- ACTIONS THE INSTALLED SDK DEFINES (authoritative: read from @servicenow/sdk-core) ---');
  lines.push('Only these exist. `required` is what the SDK marks mandatory; outputs are CASE-SENSITIVE.');
  for (const [key, a] of Object.entries(catalogue.actions).sort(([a1], [a2]) => a1.localeCompare(a2))) {
    const req = a.inputs.filter((i) => i.mandatory).map((i) => i.name);
    const opt = a.inputs.filter((i) => !i.mandatory).map((i) => i.name);
    const out = a.outputs.map((o) => o.name);
    lines.push(
      `action.core.${key}`
      + (req.length ? `  required: ${req.join(', ')}` : '  required: (none)')
      + (opt.length ? `  |  optional: ${opt.join(', ')}` : '')
      + (out.length ? `  ->  ${out.join(', ')}` : '  ->  (no outputs)')
    );
  }
  lines.push('');
  lines.push('--- TRIGGERS THE INSTALLED SDK DEFINES ---');
  for (const [key, t] of Object.entries(catalogue.triggers).sort(([a1], [a2]) => a1.localeCompare(a2))) {
    const req = t.inputs.filter((i) => i.mandatory).map((i) => i.name);
    const opt = t.inputs.filter((i) => !i.mandatory).map((i) => i.name);
    lines.push(
      `trigger.${t.family}.${key}`
      + (req.length ? `  required: ${req.join(', ')}` : '  required: (none)')
      + (opt.length ? `  |  optional: ${opt.join(', ')}` : '')
    );
  }
  lines.push('There is no record-deleted trigger; the SDK defines no such thing.');
  return lines.join('\n');
}
